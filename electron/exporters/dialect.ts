import type { ColumnType, ExportTargetKind } from '../../shared/ipc-types'

/** SQL 方言配置表：标识符引用、布尔/日期字面量、列类型映射、自增列、批量插入与事务包裹。 */

export interface Dialect {
  kind: Exclude<ExportTargetKind, 'csv' | 'sqlite' | 'mongodb'>
  quote: (id: string) => string
  typeOf: (t: ColumnType) => string
  boolLiteral: (v: string) => string
  dateLiteral: (v: string) => string
  autoIncrementClause: string
  batchSize: number
  wrapTransaction: boolean
}

const DIALECTS: Record<Dialect['kind'], Dialect> = {
  mysql: {
    kind: 'mysql',
    quote: (id) => `\`${id.replace(/`/g, '``')}\``,
    typeOf: (t) =>
      t === 'text'
        ? 'TEXT'
        : t === 'integer'
          ? 'BIGINT'
          : t === 'real'
            ? 'DOUBLE'
            : t === 'date'
              ? 'DATETIME'
              : 'TINYINT(1)',
    boolLiteral: (v) => (v === 'true' || v === '1' ? '1' : '0'),
    dateLiteral: (v) => `'${v.replace(/'/g, "''")}'`,
    autoIncrementClause: 'AUTO_INCREMENT',
    batchSize: 500,
    wrapTransaction: true
  },
  postgresql: {
    kind: 'postgresql',
    quote: (id) => `"${id.replace(/"/g, '""')}"`,
    typeOf: (t) =>
      t === 'text'
        ? 'TEXT'
        : t === 'integer'
          ? 'BIGINT'
          : t === 'real'
            ? 'DOUBLE PRECISION'
            : t === 'date'
              ? 'TIMESTAMP'
              : 'BOOLEAN',
    boolLiteral: (v) => (v === 'true' || v === '1' ? 'TRUE' : 'FALSE'),
    dateLiteral: (v) => `'${v.replace(/'/g, "''")}'`,
    autoIncrementClause: 'GENERATED BY DEFAULT AS IDENTITY',
    batchSize: 500,
    wrapTransaction: true
  },
  sqlserver: {
    kind: 'sqlserver',
    quote: (id) => `[${id.replace(/]/g, ']]')}]`,
    typeOf: (t) =>
      t === 'text'
        ? 'NVARCHAR(MAX)'
        : t === 'integer'
          ? 'BIGINT'
          : t === 'real'
            ? 'FLOAT'
            : t === 'date'
              ? 'DATETIME2'
              : 'BIT',
    boolLiteral: (v) => (v === 'true' || v === '1' ? '1' : '0'),
    dateLiteral: (v) => `'${v.replace(/'/g, "''")}'`,
    autoIncrementClause: 'IDENTITY(1,1)',
    batchSize: 500,
    wrapTransaction: true
  }
}

/** 按目标数据库取方言配置；CSV/SQLite/MongoDB 不生成 SQL 脚本，调用即报错。 */
export function getDialect(kind: ExportTargetKind): Dialect {
  const d = DIALECTS[kind as Dialect['kind']]
  if (!d) throw new Error(`目标类型 ${kind} 不生成 SQL 脚本`)
  return d
}

/** SQL 字面量转义（文本值） */
export function sqlStringLiteral(v: string): string {
  return `'${v.replace(/'/g, "''")}'`
}
